-- Evaluates Questie's quest blacklist for WoW Forever and writes
-- WalkMap_QuestBlacklist.lua. Not loaded by the game.
-- Usage (Lua 5.1-5.4): lua gen.lua <Questie folder> <output file> <Questie version>
local root = arg_root or arg[1]
arg_out = arg_out or arg[2]
arg_source = arg_source or ("Questie " .. tostring(arg[3] or "?"))
local modules = {}
QuestieLoader = {
  CreateModule = function(_, name) modules[name] = modules[name] or {}; return modules[name] end,
  ImportModule = function(_, name) modules[name] = modules[name] or {}; return modules[name] end,
}
Questie = {IsForever = true, IsChinaRegion = false, Debug = function() end, DEBUG_DEVELOP = 0}
GetLocale = function() return "enUS" end
dofile(root .. "/Modules/Expansions.lua")
local ok, err = pcall(dofile, root .. "/Database/Corrections/ContentPhases/ContentPhases.lua")
if not ok then
  modules.ContentPhases.activePhases = modules.ContentPhases.activePhases or {SoM=5,SoD=7,Anniversary=6,MoP=5,TBC=4}
  io.stderr:write("ContentPhases stubbed: " .. tostring(err) .. "\n")
end
dofile(root .. "/Database/Corrections/QuestieQuestBlacklist.lua")
local list = modules.QuestieQuestBlacklist:Load()
local ids, hide, mapOnly = {}, 0, 0
for id, flag in pairs(list) do
  if flag == true then ids[#ids + 1] = id; hide = hide + 1
  elseif flag == "HIDE_ON_MAP" then ids[#ids + 1] = id; mapOnly = mapOnly + 1 end
end
table.sort(ids)
local out = assert(io.open(arg_out, "w"))
out:write("-- SPDX-License-Identifier: GPL-3.0-or-later\n")
out:write("-- WalkMap: static copy of Questie's quest blacklist, evaluated for WoW Forever\n")
out:write("-- (Era content, enUS, no SoD/TBC/Anniversary/Hardcore branches).\n")
out:write("-- Source: " .. arg_source .. " Database/Corrections/QuestieQuestBlacklist.lua.\n")
out:write("-- Derived from Questie (GPLv3, the Questie contributors); distributed with\n")
out:write("-- WalkMap under GPL-3.0-or-later. See THIRD_PARTY_NOTICES.txt.\n")
out:write("-- Generated by tools/QuestBlacklist/gen.lua.\n")
out:write("-- Regenerate from a newer Questie when it updates. When Questie itself is\n")
out:write("-- loaded, WalkMap uses Questie's live list (which also knows active events).\n")
out:write(string.format("-- %d hidden quests, %d hidden on maps only.\n", hide, mapOnly))
out:write("WalkMapQuestBlacklist = {\n")
local line = {}
for _, id in ipairs(ids) do
  line[#line + 1] = string.format("[%d]=%s", id, list[id] == true and "1" or "2")
  if #line == 10 then out:write("  " .. table.concat(line, ",") .. ",\n"); line = {} end
end
if #line > 0 then out:write("  " .. table.concat(line, ",") .. ",\n") end
out:write("}\n-- 1 = hidden, 2 = hidden on maps (HIDE_ON_MAP); both hide map markers.\n")
out:close()
print(string.format("ids=%d hide=%d mapOnly=%d", #ids, hide, mapOnly))
